#!/usr/bin/env python3
"""Turns Roblox's API dump into mixins/horizon_studio/rbx_api_data.rs.

The Roblox layer implements the classes and members scripts use most by
hand (rbx.rs); every other class, property, method, event, callback and
enum Roblox has comes from this table, with its value type and default.

    curl -sSfL -o dump.json \
      https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json
    python3 tools/gen_api.py dump.json

Lines (tab-separated):
    C name superclass flags     flags: n not creatable, s service
    P name category type default flags     flags: r read-only, h not scriptable
    F name category type        a method; the type is what it returns
    E name                      an event
    B name                      a callback (a property a function is set to)
    N name                      an enum
    I name value                one of its items
"""
import json
import sys
from pathlib import Path


def clean(s):
    return str(s).replace("\t", " ").replace("\n", " ").replace("\r", " ")


def main():
    dump = json.load(open(sys.argv[1]))
    out = []
    for c in dump["Classes"]:
        tags = c.get("Tags") or []
        flags = ("n" if "NotCreatable" in tags else "") + ("s" if "Service" in tags else "")
        out.append(f"C\t{c['Name']}\t{c.get('Superclass', '<<<ROOT>>>')}\t{flags}")
        for m in c.get("Members", []):
            kind = m["MemberType"]
            mtags = m.get("Tags") or []
            name = clean(m["Name"])
            if kind == "Property":
                vt = m["ValueType"]
                f = ""
                if "ReadOnly" in mtags:
                    f += "r"
                if "NotScriptable" in mtags:
                    f += "h"
                default = clean(m.get("Default", "")) if m.get("Default") is not None else ""
                if default.startswith("__api_dump"):
                    default = ""
                out.append(f"P\t{name}\t{vt['Category']}\t{vt['Name']}\t{default}\t{f}")
            elif kind == "Function":
                rt = m.get("ReturnType", {"Category": "Primitive", "Name": "void"})
                if isinstance(rt, list):
                    rt = rt[0] if rt else {"Category": "Primitive", "Name": "void"}
                out.append(f"F\t{name}\t{rt['Category']}\t{rt['Name']}")
            elif kind == "Event":
                out.append(f"E\t{name}")
            elif kind == "Callback":
                out.append(f"B\t{name}")
    for e in dump["Enums"]:
        out.append(f"N\t{e['Name']}")
        for i in e["Items"]:
            out.append(f"I\t{clean(i['Name'])}\t{i['Value']}")
    text = "\n".join(out) + "\n"
    assert '"###' not in text
    rs = (
        "// Generated by tools/gen_api.py from Roblox's API dump "
        f"(version {clean(dump.get('Version', '?'))}); do not edit.\n"
        "// Every class, member and enum Roblox has, for the Roblox layer's\n"
        "// classes and members rbx.rs doesn't implement itself (rbx_api.rs).\n\n"
        f'pub const API: &str = r###"{text}"###;\n'
    )
    dest = Path(__file__).resolve().parent.parent / "mixins" / "horizon_studio" / "rbx_api_data.rs"
    dest.write_text(rs)
    print(f"{dest}: {len(rs)} bytes, {len(out)} lines")


if __name__ == "__main__":
    main()
